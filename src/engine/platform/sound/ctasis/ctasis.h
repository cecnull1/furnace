#ifndef COM_GITHUB_CECNULL1_CTASIS_H
#define COM_GITHUB_CECNULL1_CTASIS_H
#include <stdint.h>

// Cecnull1 - Tasis Synth

#define OPER_PHASES 16
#define OPER_PITCHS 16
#define OPER_NUMBER 8
#define OUT_CHANNEL_NUMBER 2
#define FILTER_NUMBER 4

typedef uint16_t TASIS_REG;
typedef uint32_t TASIS_DOUBLE_REG;

struct TASIS_CHANNEL {
    // OP
    TASIS_DOUBLE_REG OP_PHASE[OPER_NUMBER][OPER_PHASES];
    TASIS_DOUBLE_REG OP_PITCH[OPER_NUMBER][OPER_PITCHS];
    TASIS_DOUBLE_REG OP_PCM_START[OPER_NUMBER];
    TASIS_DOUBLE_REG OP_PCM_END[OPER_NUMBER];
    TASIS_REG OP_MI_SQUARE[OPER_NUMBER][OPER_NUMBER];
    TASIS_DOUBLE_REG OP_ENVELOPE_START[OPER_NUMBER];
    TASIS_DOUBLE_REG OP_ENVELOPE_END[OPER_NUMBER];
    TASIS_DOUBLE_REG OP_ENVELOPE_END_2[OPER_NUMBER];
    TASIS_DOUBLE_REG OP_ENVELOPE_PHASE[OPER_NUMBER];
    TASIS_REG OP_ENVELOPE_PHASE_LOW[OPER_NUMBER];
    TASIS_REG OP_ENVELOPE_STATE[OPER_NUMBER];
    TASIS_REG OP_ENVELOPE_STEP[OPER_NUMBER];
    TASIS_REG OP_FLAGS[OPER_NUMBER];
    TASIS_REG OP_DUTY[OPER_NUMBER];
    TASIS_DOUBLE_REG OP_VFB[OPER_NUMBER];


    // TODO: FILTER
    double FILTER_BUF_LOW[FILTER_NUMBER];
    double FILTER_BUF_BAND[FILTER_NUMBER];
    TASIS_REG FILTER_VOLUME_OUT[FILTER_NUMBER][OPER_NUMBER];
    TASIS_REG CUTOFF[FILTER_NUMBER];
    TASIS_REG RES[FILTER_NUMBER];
    TASIS_REG FILTER_IN_S[OPER_NUMBER+FILTER_NUMBER][OUT_CHANNEL_NUMBER];

    // MIXER
    TASIS_REG VOLUME_OPER_IN_S[OPER_NUMBER][OUT_CHANNEL_NUMBER];
    TASIS_REG VOLUME_OUT[OUT_CHANNEL_NUMBER];
    TASIS_DOUBLE_REG TASIS_BUFFER_OUT[OUT_CHANNEL_NUMBER];
};

void TASIS_CLOCK(struct TASIS_CHANNEL*);

#endif //COM_GITHUB_CECNULL1_CTASIS_H